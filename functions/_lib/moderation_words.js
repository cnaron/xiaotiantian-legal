/** 会被当成「插入符」抹掉的字符(见顶部原则 4)。注意不含 `,。、!?` */
const SEP_20260909 = /[\s​-‏⁠﻿*·・.~^_+=|/\\'"`,\-—–]/g;

/**
 * 归一化。返回两个串:
 *   raw      = NFKC + 小写(全角→半角、① → 1 之类都归了)
 *   stripped = raw 再抹掉插入符
 */
export function normalizeForMatch_claudecode_20260909(s) {
  let raw = String(s == null ? '' : s);
  try { raw = raw.normalize('NFKC'); } catch (e) { /* 极老运行时没有 normalize,退化成原串 */ }
  raw = raw.toLowerCase();
  return { raw, stripped: raw.replace(SEP_20260909, '') };
}

